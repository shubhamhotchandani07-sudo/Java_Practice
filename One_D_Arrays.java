    //Array me sabse chhota positive number count karo
    public static void main(String[] args) {
        int [] a = {1,2,-3,0,-1,9};

    int positive_count=0;
    int min=a[0];
    for(int i=0;i<a.length;i++){
        if (a[i]>0 ) {
            positive_count+=1;
            
        }
        else if (a[i]>min) {
            min=a[i];
        }
        
    
    }
    System.out.println(positive_count);
    System.out.println(min);
}
