public class Literals {
    public static void main(String[] args) {
        //Literals --> A Constant Value Which Is Stored in a Variables
        int age = 42;
        System.out.println(age);

        //This 42 is called a Literal Because It Having A Constant Value == "42"

        short age2=43;
        System.out.println(age2);
         
        String str="Shubham";
        System.out.println(str);
    }
}
